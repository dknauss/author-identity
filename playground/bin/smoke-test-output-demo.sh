#!/usr/bin/env bash
# Smoke-test a running output-demo Playground.
#
# Checks that each demo route answers and carries the Byline Feed output the
# demo posts tell readers to look for. Start the demo first, for example:
#
#   npx @wp-playground/cli@3.1.60 server \
#     --blueprint=playground/output-demo.blueprint.json --port=9400
#
# Usage: playground/bin/smoke-test-output-demo.sh [base-url]
# The base URL defaults to http://127.0.0.1:9400.

set -euo pipefail

BASE_URL="${1:-http://127.0.0.1:9400}"
BASE_URL="${BASE_URL%/}"
failures=0

# check <label> <path> <fixed string that must appear in the response body>
check() {
	local label="$1" path="$2" needle="$3" body

	if ! body="$(curl --silent --show-error --fail --location --max-time 60 "${BASE_URL}${path}")"; then
		echo "FAIL  ${label}: ${path} did not return 2xx"
		failures=$((failures + 1))
		return
	fi

	if grep -qF -- "$needle" <<<"$body"; then
		echo "ok    ${label}: found '${needle}'"
	else
		echo "FAIL  ${label}: '${needle}' not found at ${path}"
		failures=$((failures + 1))
	fi
}

check "Allowed post"         "/?p=1"           'name="fediverse:creator"'
check "Allowed post"         "/?p=1"           'application/ld+json'
check "RSS2 feed"            "/?feed=rss2"     'xmlns:byline="https://bylinespec.org/1.0"'
check "RSS2 feed"            "/?feed=rss2"     '<byline:contributors>'
check "Atom feed"            "/?feed=atom"     'xmlns:byline="https://bylinespec.org/1.0"'
check "JSON Feed"            "/?feed=json"     '"_byline"'
check "Author-consent deny"  "/?p=101"         'noai, noimageai'
check "Post-override deny"   "/?p=102"         'noai, noimageai'
check "ai.txt"               "/ai.txt"         '# ai.txt generated by Byline Feed'

if [ "$failures" -gt 0 ]; then
	echo "${failures} check(s) failed."
	exit 1
fi

echo "All output-demo checks passed."
